#!/usr/bin/env python3
"""Predict Heavy--Ball coefficients directly from the PDE/forcing law.

Unlike a calibration-set fit, this program never consumes observed prompts.
It uses the known operator prior, Gaussian forcing covariance, learned weak
dictionary, probes, and one-head preconditioner to construct two laws:

1. the conditional-population law obtained from exact Gaussian moments;
2. an exact synthetic prompt law used only to audit the population closure.

The first law is the low-assumption finite-K predictor.  The second quantifies
the finite-prompt correction without pretending that the mR weak rows are iid.
For every requested depth, only the two stable Heavy--Ball scalars are
optimized through the exact residual recurrence.
"""

