Tensor = torch.Tensor


def parse_depths(value: str) -> list[int]:
    depths = sorted({int(item) for item in value.split(",") if item.strip()})
    if not depths or depths[0] <= 0:
        raise ValueError("depth-grid must contain positive integers")
    return depths


def weak_row_map(learned_basis: Tensor, probes: Tensor) -> Tensor:
    """Return L[r,k,:] such that g_{r,k}=L[r,k,:] u."""

    return torch.einsum("rd,kde->rke", probes, learned_basis)


def conditional_weak_moments(
    true_operator: Tensor,
    learned_A0: Tensor,
    learned_basis: Tensor,
    probes: Tensor,
    forcing_variance: float,
) -> tuple[Tensor, Tensor]:
    """Exact per-forcing E[G_i^T G_i|z] and E[G_i^T b_i|z].

    All R weak rows generated by one forcing share the same state u.  The
    contractions below retain that dependence exactly.
    """

    batch, dimension, _ = true_operator.shape
    identity = torch.eye(
        dimension,
        device=true_operator.device,
        dtype=true_operator.dtype,
    ).expand(batch, -1, -1)
    inverse = torch.linalg.solve(true_operator, identity)
    state_covariance = (
        forcing_variance * inverse @ inverse.transpose(-1, -2)
    )
    rows = weak_row_map(learned_basis, probes)
    mean_normal = torch.einsum(
        "rki,bij,rlj->bkl",
        rows,
        state_covariance,
        rows,
    )
    rhs_rows = torch.einsum(
        "rd,bde->bre",
        probes,
        true_operator - learned_A0,
    )
    mean_rhs = torch.einsum(
        "rki,bij,brj->bk",
        rows,
        state_covariance,
        rhs_rows,
    )
    return mean_normal, mean_rhs


def exact_prompt_normal_rhs(
    true_operator: Tensor,
    learned_A0: Tensor,
    learned_basis: Tensor,
    probes: Tensor,
    prompt_length: int,
    forcing_std: float,
    generator: torch.Generator,
) -> tuple[Tensor, Tensor]:
    """Draw the exact matrix-valued quadratic prompt law conditional on z."""

    batch, dimension, _ = true_operator.shape
    forcing = torch.randn(
        batch,
        prompt_length,
        dimension,
        device=true_operator.device,
        dtype=true_operator.dtype,
        generator=generator,
    ) * forcing_std
    state = torch.linalg.solve(
        true_operator,
        forcing.transpose(-1, -2),
    ).transpose(-1, -2)
    rows = weak_row_map(learned_basis, probes)
    equations = torch.einsum(
        "rke,bme->bmrk",
        rows,
        state,
    ).flatten(1, 2)
    learned_A0_state = torch.einsum("de,bme->bmd", learned_A0, state)
    observations = torch.einsum(
        "rd,bmd->bmr",
        probes,
        forcing - learned_A0_state,
    ).flatten(1, 2)
    normal = equations.transpose(-1, -2) @ equations
    rhs = torch.einsum("bmk,bm->bk", equations, observations)
    return normal, rhs


def physical_linearized_gram(
    model,
    normal_matrix: Tensor,
    rhs: Tensor,
    cholesky_preconditioner: Tensor,
    eigenvectors: Tensor,
    spectral_solution: Tensor,
    query_forcing: Tensor,
) -> Tensor:
    """Gram Q with ||J e_L||^2/d = p(lambda)^T Q p(lambda).

    J is the exact derivative of the ridge forward solve at the encoded exact
    coefficient solution.  Only the downstream nonlinear remainder is omitted.
    """

    coefficient = torch.linalg.solve(
        normal_matrix,
        rhs.unsqueeze(-1),
    ).squeeze(-1)
    operator = model.A0.unsqueeze(0) + torch.einsum(
        "bk,kij->bij",
        coefficient,
        model.Abasis,
    )
    dimension = operator.shape[-1]
    identity = torch.eye(
        dimension,
        device=operator.device,
        dtype=operator.dtype,
    )
    # ridge_forward_solve adds a fixed 1e-7 numerical jitter.
    forward_normal = (
        operator.transpose(-1, -2) @ operator
        + (model.gamma_u + 1e-7) * identity
    )
    forward_rhs = torch.einsum(
        "bji,bj->bi",
        operator,
        query_forcing,
    )
    state = torch.linalg.solve(
        forward_normal,
        forward_rhs.unsqueeze(-1),
    ).squeeze(-1)
    operator_state = torch.einsum("bij,bj->bi", operator, state)
    basis_state = torch.einsum("kij,bj->bki", model.Abasis, state)
    derivative_rhs = (
        torch.einsum("kji,bj->bki", model.Abasis, query_forcing)
        - torch.einsum("kji,bj->bki", model.Abasis, operator_state)
        - torch.einsum("bji,bkj->bki", operator, basis_state)
    )
    jacobian = torch.linalg.solve(
        forward_normal,
        derivative_rhs.transpose(-1, -2),
    )
    routed_jacobian = torch.einsum(
        "bdk,bkj,bji->bdi",
        jacobian,
        cholesky_preconditioner,
        eigenvectors,
    )
    weighted = routed_jacobian * spectral_solution[:, None, :]
    return torch.einsum(
        "bdi,bdj->bij",
        weighted,
        weighted,
    ) / dimension


@torch.no_grad()
def spectral_risk_data(
    model,
    normal_matrix: Tensor,
    rhs: Tensor,
    query_forcing: Tensor | None,
) -> tuple[Tensor, Tensor]:
    """Return effective eigenvalues and either energy weights or physical Q."""

    batch, dimension, _ = normal_matrix.shape
    dummy_equations = normal_matrix.new_empty(batch, 0, dimension)
    preconditioner, _ = model.loop_decoder.preconditioner_head(
        dummy_equations,
        normal_matrix,
    )
    identity = torch.eye(
        dimension,
        device=normal_matrix.device,
        dtype=normal_matrix.dtype,
    )
    factor = torch.linalg.cholesky(preconditioner + 1e-10 * identity)
    effective = factor.transpose(-1, -2) @ normal_matrix @ factor
    effective = 0.5 * (effective + effective.transpose(-1, -2))
    eigenvalues, eigenvectors = torch.linalg.eigh(effective)
    transformed_rhs = torch.einsum("bji,bj->bi", factor, rhs)
    spectral_rhs = torch.einsum(
        "bji,bj->bi",
        eigenvectors,
        transformed_rhs,
    )
    spectral_solution = spectral_rhs / eigenvalues.clamp_min(1e-12)
    if query_forcing is None:
        energy = eigenvalues * spectral_solution.square()
        risk_data = energy / energy.sum(dim=-1, keepdim=True).clamp_min(1e-30)
    else:
        risk_data = physical_linearized_gram(
            model,
            normal_matrix,
            rhs,
            factor,
            eigenvectors,
            spectral_solution,
            query_forcing,
        )
    return eigenvalues.double(), risk_data.double()


def task_risk(
    eigenvalues: Tensor,
    risk_data: Tensor,
    depth: int,
    step: Tensor,
    momentum: Tensor,
) -> Tensor:
    residual = hb_residual_polynomial(
        eigenvalues,
        depth,
        step,
        momentum,
    )
    if risk_data.ndim == 2:
        return (risk_data * residual.square()).sum(dim=-1)
    return torch.einsum("bi,bij,bj->b", residual, risk_data, residual)


def chebyshev_task_risk(
    eigenvalues: Tensor,
    risk_data: Tensor,
    depth: int,
    lower: Tensor,
    upper: Tensor,
) -> Tensor:
    """Risk of the exact Chebyshev scalar recurrence for taskwise intervals."""

    center = 0.5 * (upper + lower)
    half_width = 0.5 * (upper - lower)
    quarter_half_width_squared = 0.25 * half_width.square()
    step = center.reciprocal()
    momentum = torch.zeros_like(step)
    previous = torch.ones_like(eigenvalues)
    current = torch.ones_like(eigenvalues)
    for _ in range(depth):
        following = (
            (1.0 + momentum[:, None] - step[:, None] * eigenvalues)
            * current
            - momentum[:, None] * previous
        )
        next_step = (
            center - quarter_half_width_squared * step
        ).reciprocal()
        next_momentum = quarter_half_width_squared * step * next_step
        previous, current = current, following
        step, momentum = next_step, next_momentum
    if risk_data.ndim == 2:
        return (risk_data * current.square()).sum(dim=-1)
    return torch.einsum("bi,bij,bj->b", current, risk_data, current)


def summarize_task_risk(values: Tensor, cvar_fraction: float) -> Dict[str, float]:
    tail_count = max(1, math.ceil(cvar_fraction * values.numel()))
    return {
        "mean_risk": values.mean().item(),
        "cvar_risk": values.topk(tail_count).values.mean().item(),
        "median_risk": values.median().item(),
        "q99_risk": torch.quantile(values, 0.99).item(),
        "max_risk": values.max().item(),
    }


def chebyshev_interval_audit(
    laws,
    depths: Iterable[int],
    cvar_fraction: float,
) -> Dict:
    if "exact_prompt_law" not in laws:
        return {}
    population_eigenvalues, _ = laws["conditional_population"]
    exact_eigenvalues, exact_risk_data = laws["exact_prompt_law"]
    population_lower = population_eigenvalues[:, 0]
    population_upper = population_eigenvalues[:, -1]
    exact_lower = exact_eigenvalues[:, 0]
    exact_upper = exact_eigenvalues[:, -1]
    covered = (
        (exact_lower >= population_lower)
        & (exact_upper <= population_upper)
    )
    output = {
        "population_interval_exact_prompt_coverage": covered.double().mean().item(),
        "exact_to_population_lower_ratio": spectral_summary(
            (exact_lower / population_lower).unsqueeze(-1)
        ),
        "exact_to_population_upper_ratio": spectral_summary(
            (exact_upper / population_upper).unsqueeze(-1)
        ),
        "depths": {},
    }
    for depth in depths:
        predicted = chebyshev_task_risk(
            exact_eigenvalues,
            exact_risk_data,
            depth,
            population_lower,
            population_upper,
        )
        oracle = chebyshev_task_risk(
            exact_eigenvalues,
            exact_risk_data,
            depth,
            exact_lower,
            exact_upper,
        )
        output["depths"][str(depth)] = {
            "population_interval_on_exact_prompt": summarize_task_risk(
                predicted,
                cvar_fraction,
            ),
            "exact_prompt_oracle_interval": summarize_task_risk(
                oracle,
                cvar_fraction,
            ),
        }
    return output


def risk_objective(
    eigenvalues: Tensor,
    risk_data: Tensor,
    depth: int,
    raw_step: Tensor,
    raw_momentum: Tensor,
    lmax: float,
    cvar_fraction: float,
    cvar_weight: float,
) -> tuple[Tensor, Tensor, Tensor, Tensor, Tensor]:
    step, momentum = coefficients(raw_step, raw_momentum, lmax)
    per_task = task_risk(
        eigenvalues,
        risk_data,
        depth,
        step,
        momentum,
    )
    tail_count = max(1, math.ceil(cvar_fraction * per_task.numel()))
    cvar = per_task.topk(tail_count).values.mean()
    value = per_task.mean() + cvar_weight * cvar
    return value, per_task.mean(), cvar, step, momentum


def optimize_depth(
    eigenvalues: Tensor,
    risk_data: Tensor,
    depth: int,
    lmax: float,
    current_step: float,
    current_momentum: float,
    args,
) -> Dict[str, float]:
    spectral_min = eigenvalues.min().item()
    spectral_max = eigenvalues.max().item()
    sqrt_min = math.sqrt(spectral_min)
    sqrt_max = math.sqrt(spectral_max)
    minimax_step = 4.0 / (sqrt_max + sqrt_min) ** 2
    minimax_momentum = (
        (sqrt_max - sqrt_min) / (sqrt_max + sqrt_min)
    ) ** 2
    starts = [
        (current_step, current_momentum),
        (minimax_step, minimax_momentum),
        (0.5 * minimax_step, 0.25 * minimax_momentum),
        (0.8 * minimax_step, 0.5 * minimax_momentum),
        (1.1 * minimax_step, min(0.95, 1.25 * minimax_momentum)),
    ][: args.restarts]
    best = None
    for restart, (initial_step, initial_momentum) in enumerate(starts):
        raw_values = inverse_parameterization(
            initial_step,
            initial_momentum,
            lmax,
        )
        raw_step = torch.tensor(
            raw_values[0],
            dtype=torch.float64,
            device=eigenvalues.device,
            requires_grad=True,
        )
        raw_momentum = torch.tensor(
            raw_values[1],
            dtype=torch.float64,
            device=eigenvalues.device,
            requires_grad=True,
        )
        optimizer = torch.optim.Adam(
            [raw_step, raw_momentum],
            lr=args.lr,
        )
        for _ in range(args.steps):
            values = risk_objective(
                eigenvalues,
                risk_data,
                depth,
                raw_step,
                raw_momentum,
                lmax,
                args.cvar_fraction,
                args.cvar_weight,
            )
            optimizer.zero_grad(set_to_none=True)
            values[0].backward()
            optimizer.step()
        with torch.no_grad():
            values = risk_objective(
                eigenvalues,
                risk_data,
                depth,
                raw_step,
                raw_momentum,
                lmax,
                args.cvar_fraction,
                args.cvar_weight,
            )
            candidate = {
                "restart": restart,
                "depth": depth,
                "objective": values[0].item(),
                "mean_risk": values[1].item(),
                "cvar_risk": values[2].item(),
                "step": values[3].item(),
                "momentum": values[4].item(),
                "raw_step": raw_step.item(),
                "raw_momentum": raw_momentum.item(),
                "minimax_step": minimax_step,
                "minimax_momentum": minimax_momentum,
            }
        if best is None or candidate["objective"] < best["objective"]:
            best = candidate
    assert best is not None
    best["latency_aware_objective"] = (
        best["objective"] + args.hvp_cost_weight * depth
    )
    return best


@torch.no_grad()
def collect_model_laws(model, family, saved, args, device):
    coefficient_dimension = saved["K"]
    state_dimension = saved["d"]
    ridge_metric = model.coefficient_ridge_metric()
    if ridge_metric is None:
        ridge_metric = torch.eye(
            coefficient_dimension,
            device=device,
            dtype=model.A0.dtype,
        )
    z_generator = torch.Generator(device=device).manual_seed(args.seed)
    forcing_generator = torch.Generator(device=device).manual_seed(args.seed + 1)
    query_generator = torch.Generator(device=device).manual_seed(args.seed + 2)
    population_eigenvalues = []
    population_risk = []
    exact_eigenvalues = []
    exact_risk = []
    remaining = args.tasks
    while remaining > 0:
        batch = min(args.batch_size, remaining)
        log_scale = (
            math.log(args.z_scale_min)
            + (
                math.log(args.z_scale_max)
                - math.log(args.z_scale_min)
            )
            * torch.rand(
                batch,
                1,
                device=device,
                dtype=model.A0.dtype,
                generator=z_generator,
            )
        )
        coefficient = torch.randn(
            batch,
            coefficient_dimension,
            device=device,
            dtype=model.A0.dtype,
            generator=z_generator,
        ) * log_scale.exp()
        true_operator = assemble_A(
            family.A0,
            family.Abasis,
            coefficient,
        )
        mean_normal, mean_rhs = conditional_weak_moments(
            true_operator,
            model.A0,
            model.Abasis,
            model.probes,
            saved["f_std"] ** 2,
        )
        population_normal = (
            saved["m"] * mean_normal
            + saved["lam_z"] * ridge_metric
        )
        population_rhs = saved["m"] * mean_rhs
        query = None
        if args.risk_metric == "physical_linearized":
            query = torch.randn(
                batch,
                state_dimension,
                device=device,
                dtype=model.A0.dtype,
                generator=query_generator,
            ) * saved["f_std"]
        eigenvalues, risk = spectral_risk_data(
            model,
            population_normal,
            population_rhs,
            query,
        )
        population_eigenvalues.append(eigenvalues)
        population_risk.append(risk)

        if args.exact_prompt_validation:
            exact_normal, exact_rhs = exact_prompt_normal_rhs(
                true_operator,
                model.A0,
                model.Abasis,
                model.probes,
                saved["m"],
                saved["f_std"],
                forcing_generator,
            )
            exact_normal = exact_normal + saved["lam_z"] * ridge_metric
            eigenvalues, risk = spectral_risk_data(
                model,
                exact_normal,
                exact_rhs,
                query,
            )
            exact_eigenvalues.append(eigenvalues)
            exact_risk.append(risk)
        remaining -= batch

    laws = {
        "conditional_population": (
            torch.cat(population_eigenvalues),
            torch.cat(population_risk),
        )
    }
    if args.exact_prompt_validation:
        laws["exact_prompt_law"] = (
            torch.cat(exact_eigenvalues),
            torch.cat(exact_risk),
        )
    if args.risk_metric == "physical_linearized":
        for eigenvalues, grams in laws.values():
            del eigenvalues
            scale = torch.einsum(
                "bi,bij,bj->b",
                torch.ones(
                    grams.shape[0],
                    grams.shape[1],
                    dtype=grams.dtype,
                    device=grams.device,
                ),
                grams,
                torch.ones(
                    grams.shape[0],
                    grams.shape[1],
                    dtype=grams.dtype,
                    device=grams.device,
                ),
            ).mean().clamp_min(1e-30)
            grams.div_(scale)
    return laws


def spectral_summary(eigenvalues: Tensor) -> Dict[str, float]:
    flattened = eigenvalues.flatten()
    return {
        "min": flattened.min().item(),
        "q001": torch.quantile(flattened, 0.001).item(),
        "q01": torch.quantile(flattened, 0.01).item(),
        "median": flattened.median().item(),
        "mean": flattened.mean().item(),
        "q99": torch.quantile(flattened, 0.99).item(),
        "q999": torch.quantile(flattened, 0.999).item(),
        "max": flattened.max().item(),
    }


def law_discrepancy(reference: Tensor, approximation: Tensor) -> Dict[str, float]:
    reference_sorted = reference.flatten().sort().values
    approximation_sorted = approximation.flatten().sort().values
    if reference_sorted.shape != approximation_sorted.shape:
        raise ValueError("law discrepancy expects equal sample counts")
    difference = approximation_sorted - reference_sorted
    return {
        "wasserstein_1": difference.abs().mean().item(),
        "quantile_rmse": difference.square().mean().sqrt().item(),
        "mean_bias": difference.mean().item(),
        "lower_endpoint_bias": (
            approximation_sorted[0] - reference_sorted[0]
        ).item(),
        "upper_endpoint_bias": (
            approximation_sorted[-1] - reference_sorted[-1]
        ).item(),
    }


def write_candidates(path: Path, predictions: Dict[str, list[Dict]]) -> None:
    rows = []
    for law, candidates in predictions.items():
        for candidate in candidates:
            rows.append({"law": law, **candidate})
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--outdir", required=True)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--tasks", type=int, default=4096)
    parser.add_argument("--batch-size", type=int, default=512)
    parser.add_argument("--z-scale-min", type=float, default=0.1)
    parser.add_argument("--z-scale-max", type=float, default=1.0)
    parser.add_argument("--depth-grid", default="4,6,8,10,12,16,24,40")
    parser.add_argument(
        "--risk-metric",
        choices=["energy", "physical_linearized"],
        default="energy",
    )
    parser.add_argument("--cvar-fraction", type=float, default=0.05)
    parser.add_argument("--cvar-weight", type=float, default=2.0)
    parser.add_argument("--hvp-cost-weight", type=float, default=0.0)
    parser.add_argument("--steps", type=int, default=800)
    parser.add_argument("--lr", type=float, default=3e-2)
    parser.add_argument("--restarts", type=int, default=5)
    parser.add_argument("--seed", type=int, default=47000)
    parser.add_argument("--exact-prompt-validation", type=int, default=1)
    args = parser.parse_args()
    if args.tasks <= 0 or args.batch_size <= 0:
        raise ValueError("tasks and batch-size must be positive")
    if not 0 < args.z_scale_min <= args.z_scale_max:
        raise ValueError("invalid z-scale interval")
    depths = parse_depths(args.depth_grid)
    args.exact_prompt_validation = bool(args.exact_prompt_validation)

    device = torch.device(
        args.device
        if args.device == "cpu" or torch.cuda.is_available()
        else "cpu"
    )
    source = torch.load(args.checkpoint, map_location=device, weights_only=True)
    saved = copy.deepcopy(source["args"])
    if saved["solver"] != "primal_loop_heavy_ball":
        raise ValueError("checkpoint must use global primal_loop_heavy_ball")
    if bool(saved.get("adaptive_heavy_ball", 0)):
        raise ValueError("adaptive HB has no global two-scalar predictor")
    if saved.get("noise_std", 0.0) != 0.0:
        raise ValueError("the current exact moment closure assumes noiseless states")
    if saved.get("loop_preconditioner_head") != "equivariant_ritz_softmax":
        raise ValueError("the PDE-law closure requires the equivariant spectral head")

    set_seed(saved["seed"])
    family = make_true_family(
        saved["d"],
        saved["K"],
        saved["basis_scale"],
        saved["A0_scale"],
        device,
        operator_family=saved.get("operator_family", "dense_spd"),
    )
    model = build_model(saved, family, device)
    model.load_state_dict(source["model"])
    model.eval()
    laws = collect_model_laws(model, family, saved, args, device)
    lmax = float(saved["loop_lmax_bound"])
    with torch.no_grad():
        current_step, current_momentum = (
            model.loop_decoder.heavy_ball_coefficients()
        )
    predictions = {}
    summaries = {}
    selected = {}
    for name, (eigenvalues, risk_data) in laws.items():
        if eigenvalues.max() > lmax + 1e-5:
            raise ValueError(f"{name} violates certified spectral bound")
        predictions[name] = [
            optimize_depth(
                eigenvalues,
                risk_data,
                depth,
                lmax,
                current_step.item(),
                current_momentum.item(),
                args,
            )
            for depth in depths
        ]
        selected[name] = min(
            predictions[name],
            key=lambda item: item["latency_aware_objective"],
        )
        summaries[name] = spectral_summary(eigenvalues)

    discrepancy = None
    if "exact_prompt_law" in laws:
        discrepancy = law_discrepancy(
            laws["exact_prompt_law"][0],
            laws["conditional_population"][0],
        )
    output = {
        "checkpoint": str(Path(args.checkpoint).resolve()),
        "predictor": "known PDE prior + exact conditional Gaussian moments",
        "uses_observed_calibration_prompts": False,
        "tasks": args.tasks,
        "risk_metric": args.risk_metric,
        "spectral_lmax_bound": lmax,
        "current_step": current_step.item(),
        "current_momentum": current_momentum.item(),
        "spectral_summaries": summaries,
        "population_vs_exact_prompt_law": discrepancy,
        "predictions": predictions,
        "selected": selected,
        "chebyshev_interval_audit": chebyshev_interval_audit(
            laws,
            depths,
            args.cvar_fraction,
        ),
        "args": vars(args),
    }
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "summary.json").write_text(json.dumps(output, indent=2) + "\n")
    write_candidates(outdir / "depth_candidates.csv", predictions)

    saved["pde_law_hyperparameter_prediction"] = output
    selected_depth = selected["conditional_population"]["depth"]
    for prediction in predictions["conditional_population"]:
        predicted_state = copy.deepcopy(source["model"])
        predicted_state["loop_decoder.raw_step"] = torch.tensor(
            prediction["raw_step"],
            dtype=predicted_state["loop_decoder.raw_step"].dtype,
            device=predicted_state["loop_decoder.raw_step"].device,
        )
        predicted_state["loop_decoder.raw_momentum"] = torch.tensor(
            prediction["raw_momentum"],
            dtype=predicted_state["loop_decoder.raw_momentum"].dtype,
            device=predicted_state["loop_decoder.raw_momentum"].device,
        )
        predicted_args = copy.deepcopy(saved)
        predicted_args["pde_law_selected_depth"] = prediction["depth"]
        path = outdir / f"model_pde_law_predicted_depth{prediction['depth']}.pt"
        torch.save(
            {"model": predicted_state, "args": predicted_args},
            path,
        )
        if prediction["depth"] == selected_depth:
            torch.save(
                {"model": predicted_state, "args": predicted_args},
                outdir / "model_pde_law_predicted.pt",
            )
    print(json.dumps(output, indent=2))


