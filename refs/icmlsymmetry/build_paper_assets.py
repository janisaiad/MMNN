    ax.set_yscale("log")
    ax.set_xlabel("test MSE")
    ax.set_ylabel("partial even defect")
    ax.grid(True, which="major", color="#D9D9D9", linewidth=0.45, alpha=0.8)
    ax.grid(True, which="minor", color="#EEEEEE", linewidth=0.25, alpha=0.5)
