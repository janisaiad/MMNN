def value(row: dict, key: str) -> float:
    try:
        return float(row.get(key, np.nan))
    except (TypeError, ValueError):
        return float("nan")


def is_main_row(row: dict) -> bool:
    return (
        row.get("model") == "mmnn"
        and int(row.get("width", 0)) == 512
        and str(row.get("optimizer", "")) == "adam"
        and str(row.get("train_distribution", "")) == "unpaired_uniform"
        and int(row.get("freq", 0)) == 1
    )


def display_arch(row: dict) -> str:
    model = str(row.get("model", ""))
    if model == "mlp":
        return "MLP"
    rank = int(row.get("rank", 0))
    width = int(row.get("width", 1))
    return f"RF-LR {rank}/{width}"


def sci(x: float) -> str:
    if not np.isfinite(x):
        return "--"
    if x == 0:
        return "$0$"
    exponent = int(np.floor(np.log10(abs(x))))
    mantissa = x / (10 ** exponent)
    return f"${mantissa:.2f}\\!\\times\\!10^{{{exponent}}}$"


def bold_sci(x: float) -> str:
    if not np.isfinite(x):
        return "--"
    if x == 0:
        return "$\\boldsymbol{0}$"
    exponent = int(np.floor(np.log10(abs(x))))
    mantissa = x / (10 ** exponent)
    return f"$\\boldsymbol{{{mantissa:.2f}\\!\\times\\!10^{{{exponent}}}}}$"


def maybe_bold_sci(x: float, best_value: float) -> str:
    if np.isfinite(x) and np.isfinite(best_value) and np.isclose(x, best_value, rtol=1e-12, atol=1e-18):
        return bold_sci(x)
    return sci(x)


def write_aggregate(rows: list[dict]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    fields = sorted({key for row in rows for key in row.keys()})
    with open(OUT / "all_metrics_aggregate.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    with open(OUT / "all_metrics_aggregate.json", "w") as f:
        json.dump(rows, f, indent=2)


def select_best_rows(rows: list[dict]) -> list[dict]:
    candidates = [
        row for row in rows
        if is_main_row(row)
        and int(row.get("rank", 0)) in {8, 16, 64, 128}
        and str(row.get("target")) in {"gaussian", "quadratic", "soft_axis"}
    ]
    best_by_key: dict[tuple, dict] = {}
    for row in candidates:
        key = (int(row["dim"]), str(row["target"]), int(row["rank"]))
        current = best_by_key.get(key)
        if current is None or value(row, "best_test_mse") < value(current, "best_test_mse"):
            best_by_key[key] = row
    return sorted(best_by_key.values(), key=lambda r: (int(r["dim"]), str(r["target"]), int(r["rank"])))


def write_tables(rows: list[dict]) -> None:
    reps = representative_result_rows(rows)
    reps = [
        row for row in reps
        if (int(row.get("dim", 0)), str(row.get("target")), int(row.get("rank", 0))) in {
            (2, "gaussian", 8),
            (2, "quadratic", 8),
            (3, "quadratic", 8),
            (2, "quadratic", 128),
            (3, "quadratic", 128),
        }
    ]
    with open(ROOT / "tables_generated.tex", "w") as f:
        f.write("% Auto-generated by build_paper_assets.py\n")
        f.write("\\vspace{0.1em}\n\\begin{center}\\scriptsize\n")
        f.write("\\setlength{\\tabcolsep}{2.5pt}\n")
        f.write("\\renewcommand{\\arraystretch}{1.05}\n")
        f.write("\\captionof{table}{Multidimensional batch-one protocol and representative results. No $(x,-x)$ pair is inserted during training; symmetry metrics are post-hoc on a separate symmetric grid.}\n")
        f.write("\\label{tab:method-summary}\n")
        f.write("\\resizebox{\\linewidth}{!}{%\n")
        f.write("\\begin{tabular}{@{}llcccc@{}}\\toprule\n")
        f.write("Data & model & rank & test MSE & $D_{out}$ & active $D_p$ \\\\\\midrule\n")
        for row in reps:
            target = str(row.get("target", "")).replace("gaussian", "Gauss.").replace("quadratic", "Quad.")
            data = f"{int(row['dim'])}D {target}"
            rank = int(row.get("rank", 0))
            model = "RF-LR" if rank in {8, 16} else "RF-LR ctrl."
            f.write(
                f"{data} & {model} & {rank} & "
                f"{sci(value(row, 'best_test_mse'))} & "
                f"{sci(value(row, 'best_output_neg_defect'))} & "
                f"{sci(value(row, 'best_last_partial_neg_defect'))} \\\\\n"
            )
        f.write("\\midrule\n")
        f.write("\\multicolumn{6}{@{}l@{}}{All rows: $W=512$, Adam $10^{-3}$, $10k$ epochs, batch $1$; frozen $A^{(\\ell)},b^{(\\ell)}$, train only $B^{(\\ell)}$.} \\\\\n")
        f.write("\\bottomrule\\end{tabular}%\n}\n\\end{center}\n\n")


def representative_result_rows(rows: list[dict]) -> list[dict]:
    best = select_best_rows(rows)
    low_rows = [
        row for row in best
        if (int(row["dim"]), str(row["target"]), int(row["rank"])) in {
            (2, "gaussian", 8), (2, "quadratic", 8), (2, "soft_axis", 8), (3, "quadratic", 8)
        }
    ]
    high_rows = [
        row for row in best
        if int(row.get("rank", 0)) in {64, 128}
        and str(row.get("target")) == "quadratic"
        and int(row.get("dim", 0)) in {2, 3}
    ]
    return low_rows + high_rows


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def csv_value(row: dict[str, str], key: str) -> float:
    try:
        return float(row.get(key, "nan"))
    except (TypeError, ValueError):
        return float("nan")


def plot_sumcos_targets() -> None:
    x = np.linspace(-1.0, 1.0, 1600)
    targets = [
        ("smooth", [(1.00, 2.0), (-0.35, 5.0), (0.18, 9.0)]),
        ("hard", [(0.70, 16.0), (-0.48, 32.0), (0.32, 52.0), (-0.20, 76.0)]),
    ]
    colors = ["#1B9E77", "#D95F02"]
    fig, axes = plt.subplots(1, 2, figsize=(3.35, 1.42), sharex=True, sharey=True)
    for ax, (label, terms), color in zip(axes, targets, colors):
        y = np.zeros_like(x)
        for alpha, omega in terms:
            y += alpha * np.cos(np.pi * omega * x)
        y = y / (np.max(np.abs(y)) + EPS)
        ax.plot(x, y, color=color, linewidth=1.0)
        ax.axvline(0.0, color="#222222", linewidth=0.45, alpha=0.35)
        ax.set_title(label, fontsize=8, pad=1.5)
        ax.set_xlabel("$x$")
        ax.set_xlim(-1.0, 1.0)
        ax.set_ylim(-1.08, 1.08)
        ax.set_xticks([-1.0, 0.0, 1.0])
        ax.set_yticks([-1.0, 0.0, 1.0])
        ax.grid(True, which="major", color="#D9D9D9", linewidth=0.4, alpha=0.75)
    axes[0].set_ylabel("target")
    fig.tight_layout(pad=0.18, w_pad=0.55)
    fig.savefig(OUT / "paper_sumcos_targets.png", bbox_inches="tight", pad_inches=0.02)
    plt.close(fig)


