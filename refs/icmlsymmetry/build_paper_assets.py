def plot_representative_result_bars(rows: list[dict]) -> None:
    selected = representative_result_rows(rows)
    if not selected:
        return
    labels = []
    colors = []
    metrics = {
        "test MSE": [],
        r"$D_{out}$": [],
        r"$D_p$": [],
    }
    for row in selected:
        dim = int(row["dim"])
        rank = int(row["rank"])
        target = str(row["target"]).replace("soft_axis", "soft")
        label = f"{dim}D {target}\nr{rank}"
        labels.append(label)
        colors.append("#2A6FBB" if rank in {8, 16} else "#D95F02")
        metrics["test MSE"].append(value(row, "best_test_mse") + EPS)
        metrics[r"$D_{out}$"].append(value(row, "best_output_neg_defect") + EPS)
        metrics[r"$D_p$"].append(value(row, "best_last_partial_neg_defect") + EPS)

    y = np.arange(len(labels))
    fig, axes = plt.subplots(1, 3, figsize=(3.35, 2.28), sharey=True)
    for ax, (title, vals) in zip(axes, metrics.items()):
        ax.barh(y, vals, color=colors, edgecolor="white", linewidth=0.4, height=0.72)
        ax.set_xscale("log")
        ax.set_title(title, fontsize=7.2, pad=1.5)
        ax.grid(True, axis="x", which="major", color="#D9D9D9", linewidth=0.38, alpha=0.8)
        ax.grid(True, axis="x", which="minor", color="#EEEEEE", linewidth=0.2, alpha=0.55)
        ax.tick_params(axis="x", which="major", labelsize=5.9, length=2.2)
        ax.tick_params(axis="y", length=0)
    axes[0].set_yticks(y, labels)
    axes[0].tick_params(axis="y", labelsize=5.8)
    for ax in axes[1:]:
        ax.tick_params(axis="y", labelleft=False)
    axes[0].invert_yaxis()
    handles = [
        plt.Line2D([], [], marker="s", linestyle="", color="#2A6FBB", label="low rank"),
        plt.Line2D([], [], marker="s", linestyle="", color="#D95F02", label="high rank"),
    ]
    fig.legend(handles=handles, loc="lower center", ncol=2, fontsize=6.2, bbox_to_anchor=(0.58, -0.03))
    fig.tight_layout(pad=0.12, w_pad=0.28)
    fig.savefig(OUT / "paper_representative_bars.png", bbox_inches="tight", pad_inches=0.015)
    plt.close(fig)


def plot_rank_bars(rows: list[dict]) -> None:
    filtered = [
        row for row in rows
        if is_main_row(row)
        and str(row.get("target")) == "quadratic"
        and int(row.get("dim", 0)) in {2, 3}
        and int(row.get("rank", 0)) in {8, 16, 128}
    ]
    ranks = [8, 16, 128]
    x = np.arange(len(ranks))
    width = 0.34
    vals_2d = []
    vals_3d = []
    for rank in ranks:
        vals_2d.append(np.nanmedian([value(r, "best_last_partial_neg_defect") for r in filtered if int(r["dim"]) == 2 and int(r["rank"]) == rank]))
        vals_3d.append(np.nanmedian([value(r, "best_last_partial_neg_defect") for r in filtered if int(r["dim"]) == 3 and int(r["rank"]) == rank]))
    plt.figure(figsize=(3.35, 2.55))
    plt.bar(x - width / 2, np.asarray(vals_2d) + EPS, width, label="2D", color="#2A6FBB", edgecolor="white", linewidth=0.5)
    plt.bar(x + width / 2, np.asarray(vals_3d) + EPS, width, label="3D", color="#D95F02", edgecolor="white", linewidth=0.5)
    plt.yscale("log")
    plt.xticks(x, [str(r) for r in ranks])
    plt.xlabel("rank", fontsize=7)
    plt.ylabel(r"median $D_p$", fontsize=7)
    plt.tick_params(axis="both", which="major", labelsize=6.5, length=2.5)
    plt.grid(True, axis="y", which="major", color="#D9D9D9", linewidth=0.4, alpha=0.8)
    plt.grid(True, axis="y", which="minor", color="#EEEEEE", linewidth=0.22, alpha=0.55)
    plt.legend(loc="upper left", fontsize=6.5)
    plt.tight_layout(pad=0.18)
    plt.savefig(OUT / "paper_rank_vs_partial.png", bbox_inches="tight", pad_inches=0.015)
    plt.close()


