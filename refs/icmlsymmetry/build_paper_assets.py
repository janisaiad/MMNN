def plot_weightspace_regimes() -> None:
    rows = read_csv_rows(ROOT / "results" / "weightspace_distributions" / "weightspace_classification.csv")
    rows = [
        row for row in rows
        if np.isfinite(csv_value(row, "final_test_error"))
        and np.isfinite(csv_value(row, "last_layer_active_even_mean"))
    ]
    if not rows:
        return
    order = ["partial-symmetric", "output-only/asymmetric", "intermediate", "underfit"]
    colors = {
        "partial-symmetric": "#1B9E77",
        "output-only/asymmetric": "#D95F02",
        "intermediate": "#7570B3",
        "underfit": "#8C8C8C",
    }
    labels = {
        "partial-symmetric": "partial-sym.",
        "output-only/asymmetric": "output-only",
        "intermediate": "intermediate",
        "underfit": "underfit",
    }
    rank_markers = {5: "o", 10: "s"}
    fig, ax = plt.subplots(figsize=(3.35, 2.28))
    for label in order:
        for rank, marker in rank_markers.items():
            subset = [row for row in rows if row.get("class") == label and int(csv_value(row, "rank")) == rank]
            if not subset:
                continue
            x = np.asarray([csv_value(row, "final_test_error") for row in subset])
            y = np.asarray([csv_value(row, "last_layer_active_even_mean") for row in subset])
            mismatch = np.asarray([csv_value(row, "mirror_mismatch_median") for row in subset])
            size = 20 + 16 * np.clip(mismatch, 0.0, 1.2)
            ax.scatter(
                x,
                y + EPS,
                s=size,
                marker=marker,
                color=colors[label],
                alpha=0.72,
                edgecolor="white",
                linewidth=0.35,
            )
    ax.axhline(1e-3, color="#222222", linestyle="--", linewidth=0.65, alpha=0.7)
    ax.axvline(1e-3, color="#222222", linestyle="--", linewidth=0.65, alpha=0.7)
