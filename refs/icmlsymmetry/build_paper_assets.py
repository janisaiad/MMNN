def row_best(row: dict, key: str) -> float:
    best = value(row, f"best_{key}")
    if np.isfinite(best):
        return best
    return value(row, key)


def model_group(row: dict) -> str:
    if str(row.get("model")) == "mlp":
        return "MLP"
    rank = int(row.get("rank", 0))
    if rank <= 16:
        return "RF-LR low"
    if rank >= 64:
        return "RF-LR high"
    return "RF-LR mid"


def finite_metric_rows(rows: list[dict]) -> list[dict]:
    return [
        row for row in rows
        if np.isfinite(row_best(row, "test_mse"))
        and np.isfinite(row_best(row, "last_partial_neg_defect"))
        and str(row.get("target", "")) in {"gaussian", "quadratic", "soft_axis"}
    ]


def plot_model_partial_boxes(rows: list[dict]) -> None:
    filtered = [
        row for row in finite_metric_rows(rows)
        if row_best(row, "test_mse") <= 5e-3
        and model_group(row) in {"RF-LR low", "RF-LR high", "MLP"}
    ]
    if not filtered:
        return
    groups = ["RF-LR low", "RF-LR high", "MLP"]
    distributions = ["unpaired_uniform", "positive_bias"]
    colors = {"RF-LR low": "#2A6FBB", "RF-LR high": "#D95F02", "MLP": "#6A6A6A"}
    fig, axes = plt.subplots(1, len(distributions), figsize=(3.35, 1.9), sharey=True)
    if len(distributions) == 1:
        axes = [axes]
    for ax, dist in zip(axes, distributions):
        vals = []
        labels = []
        for group in groups:
            v = [
                row_best(row, "last_partial_neg_defect") + EPS
                for row in filtered
                if model_group(row) == group and str(row.get("train_distribution", "")) == dist
            ]
            vals.append(v)
            labels.append(f"{group}\n(n={len(v)})")
        positions = np.arange(1, len(groups) + 1)
        nonempty = [v if v else [np.nan] for v in vals]
        bp = ax.boxplot(nonempty, positions=positions, widths=0.56, patch_artist=True, showfliers=False)
        for patch, group in zip(bp["boxes"], groups):
            patch.set(facecolor=colors[group], alpha=0.75, edgecolor="#222222", linewidth=0.55)
        for median in bp["medians"]:
            median.set(color="white", linewidth=1.0)
        for pos, v, group in zip(positions, vals, groups):
            if v:
                jitter = np.linspace(-0.12, 0.12, len(v)) if len(v) > 1 else np.array([0.0])
                ax.scatter(pos + jitter, v, s=10, color=colors[group], edgecolor="white", linewidth=0.25, zorder=3)
        ax.set_yscale("log")
        ax.set_xticks(positions, labels, fontsize=5.3)
        title = "unpaired uniform" if dist == "unpaired_uniform" else "positive bias"
        ax.set_title(title, fontsize=7.2, pad=1.2)
        ax.grid(True, axis="y", which="major", color="#D9D9D9", linewidth=0.35, alpha=0.75)
        ax.grid(True, axis="y", which="minor", color="#EEEEEE", linewidth=0.18, alpha=0.55)
        ax.tick_params(axis="y", labelsize=5.8, length=2.0)
    axes[0].set_ylabel("active $D_p(-x)$", fontsize=7)
    fig.tight_layout(pad=0.1, w_pad=0.25)
    fig.savefig(OUT / "paper_model_partial_boxes.png", bbox_inches="tight", pad_inches=0.012)
    plt.close(fig)


